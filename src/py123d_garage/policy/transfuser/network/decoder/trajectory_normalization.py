def pose_statistics(
    offsets_us: list[int],
) -> tuple[list[tuple[float, float, float]], list[tuple[float, float, float]]]:
    """
    Looks up the pose mean and std of 10 Hz trajectory offsets.

    Args:
        offsets_us: trajectory offsets, every 0.1 s from 0.1 s.

    Returns:
        the (x, y, yaw) mean and std of every offset.
    """
    if offsets_us != uniform_offsets_us(100_000, 100_000 * len(offsets_us)) or len(offsets_us) > len(POSE_MEAN):
        raise ValueError(
            f"trajectory_normalization holds 0.1 s offsets up to {len(POSE_MEAN) / 10} s, the policy predicts {offsets_us}.",
        )
    return POSE_MEAN[: len(offsets_us)], POSE_STD[: len(offsets_us)]
